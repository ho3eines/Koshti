/**
 * Lightweight runtime localization. Right-to-left friendly.
 *
 * All user-facing strings in the UI go through `t()`. Screens should never
 * hard-code English labels directly — that's what caused the onboarding /
 * match screens to feel English-only before.
 */

export type Lang = 'fa' | 'en';

let current: Lang = 'fa';

export const setLang = (l: Lang): void => {
  current = l;
  try {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = l;
      document.documentElement.dir = l === 'fa' ? 'rtl' : 'ltr';
      document.documentElement.classList.toggle('lang-fa', l === 'fa');
      document.documentElement.classList.toggle('lang-en', l === 'en');
    }
  } catch {
    /* ssr / tests */
  }
};

