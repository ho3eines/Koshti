/**
 * Translate a key. Falls back to English if the FA string is missing, then to
 * the supplied default string, and finally to the key itself — so a missing
 * translation never crashes.
 *
 * Supports simple {name} interpolation, e.g. t('hi.name', { name: 'Ali' }).
 */
export const t = (key: string, vars?: Record<string, string | number>, fallback?: string): string => {
  const entry = D[key];
  let s: string;
  if (!entry) {
    s = fallback ?? key;
  } else {
    s = entry[current] ?? entry.en ?? fallback ?? key;
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  // Persian numerals for that authentic feel.
  if (current === 'fa') s = toPersianDigits(s);
  return s;
};

const FA_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];

export const toPersianDigits = (s: string): string =>
  s.replace(/\d/g, (d) => FA_DIGITS[Number(d)] ?? d);

/** Convert an ASCII numeral to Persian digits for display if current lang is Persian. */
export const faNum = (n: number | string): string =>
  current === 'fa' ? toPersianDigits(String(n)) : String(n);

